const assert=require('node:assert/strict');const {plan,add,capacityFor,defaults}=require('../task-planning-core.js');
assert.equal(add('2026-10-31',1),'2026-11-01');
assert.equal(add('2028-02-28',1),'2028-02-29');
assert.equal(capacityFor('2026-10-19',{weekdays:[100,100,100,100,100,0,0],reservePercent:30}),70);
const task=(id,dueDate,minutes,mandatory=true)=>({id,title:id,dueDate,minutes,mandatory,blockedBy:[]});
let r=plan({today:'2026-10-19',tasks:[task('exam','2026-10-21',80)],settings:{weekdays:[90,90,90,90,90,0,0],reservePercent:30}});
assert.equal(r.assignments.exam.unallocated,0);
assert.deepEqual(r.assignments.exam.days.map(d=>d.date),['2026-10-20','2026-10-19']);
assert.ok(r.todayMust.some(t=>t.id==='exam'));
r=plan({today:'2026-10-19',tasks:[task('a','2026-10-19',400)],settings:{weekdays:[90,90,90,90,90,0,0],reservePercent:30}});
assert.ok(r.issues.some(i=>i.type==='overload'));
assert.ok(!r.confident);
r=plan({today:'2026-10-19',tasks:[task('a','2026-10-19',20),task('flex','2026-10-19',400,false)]});
assert.ok(!r.issues.some(i=>i.id==='flex'));
assert.equal(r.optionalToday.length,1);
r=plan({today:'2026-10-19',tasks:[{...task('fixed','2026-10-20',90),stepId:'conduct'}]});
assert.equal(r.assignments.fixed.fixed,true);
assert.equal(r.assignments.fixed.minutes,0);
r=plan({today:'2026-10-19',tasks:[task('undated','',10)]});
assert.ok(r.issues.some(i=>i.type==='no-date'));
assert.ok(!r.confident);
r=plan({today:'2026-10-19',tasks:[task('overdue','2026-10-18',10)]});
assert.ok(r.issues.some(i=>i.type==='overdue'));
r=plan({today:'2026-10-19',todayModifier:0,tasks:[task('due','2026-10-19',20)]});
assert.ok(r.issues.some(i=>i.type==='overload'));
r=plan({today:'2026-10-19',tasks:[{...task('reply','2026-10-19',10),status:'waiting'},{...task('dependent','2026-10-20',30),blockedBy:['reply']} ]});
assert.ok(r.issues.some(i=>i.type==='waiting'));
assert.ok(r.issues.some(i=>i.type==='blocked'));
assert.ok(!r.todayMust.some(t=>t.id==='reply'||t.id==='dependent'));
r=plan({today:'2026-10-19',tasks:[task('monday','2026-10-23',80)],capacityByDate:{'2026-10-19':120,'2026-10-20':0,'2026-10-21':0,'2026-10-22':0,'2026-10-23':0},segmentsByDate:{'2026-10-19':[{blockId:'school-1',startMinute:570,endMinute:690}]},preferEarlier:true});
assert.equal(r.assignments.monday.unallocated,0);
assert.equal(r.assignments.monday.slots[0].startMinute,570);
assert.equal(r.assignments.monday.slots[0].endMinute,650);
assert.equal(r.assignments.monday.slots[0].blockId,'school-1');
console.log('Native task planning capacities, block slots, waiting dependencies and issue warnings passed');