const assert=require('node:assert/strict'),c=require('../task-progress-core.js');
const root={projects:[{id:'p',title:'Synthetic lessons',tasks:[{id:'a',title:'Stunde planen',minutes:45,doneAt:null},{id:'b',title:'Klassenarbeit bewerten',doneAt:null}]}],inbox:[{id:'c',title:'Telefonliste holen',doneAt:null}]};
const at='2026-10-20T09:30:00.000Z';
let p=c.update(root,{taskId:'a',status:'progress',note:'Präsentation skizziert'},at,'manual:1');
assert.equal(root.projects[0].tasks[0].doneAt,null);assert.equal(p.note,'Präsentation skizziert');
assert.equal(c.latest(root,'a').note,'Präsentation skizziert');
const entry={id:'time-x',categoryId:'work_home',subcategory:'Lesson planning',startAt:'2026-10-20T08:00:00Z',endAt:at,minutes:90};
c.linkTimeEntry(root,entry,[{taskId:'a',status:'done',note:'GA vorbereitet'},{taskId:'c',status:'progress',note:'Rückfrage noch offen'}],at);
assert.equal(entry.taskLinks.length,2);
assert.equal(root.projects[0].tasks[0].doneAt,at);
assert.equal(root.inbox[0].doneAt,null);
assert.equal(root.taskActivityV1.length,3);
c.linkTimeEntry(root,entry,[{taskId:'a',status:'done',note:'Fertig'},{taskId:'c',status:'progress',note:'Mehr Infos nötig'}],at);
assert.equal(root.taskActivityV1.length,3,'Retry and edits do not duplicate records');
assert.equal(entry.taskLinks[0].note,'Fertig');
assert.throws(()=>c.update(root,{taskId:'unknown',status:'done'},at));
assert.throws(()=>c.linkTimeEntry(root,entry,[{taskId:'a',status:'done'},{taskId:'a',status:'done'}],at));
c.update(root,{taskId:'a',status:'reopen'},'2026-10-20T11:00:00Z','undo:1');
assert.equal(root.projects[0].tasks[0].doneAt,null);
assert.equal(c.listTasks(root,{includeDone:false}).length,3);
const suggestions=c.candidates(root,{categoryId:'work_home',subcategory:'Grading / corrections',label:'Korrekturen'});
assert.equal(suggestions[0].id,'b');
console.log('Task progress notes, time links, done/undo and duplicate safeguards passed');