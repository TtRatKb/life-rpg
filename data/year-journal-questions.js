  function indexForDate(value = new Date()) {
    const date = value instanceof Date ? value : new Date(value);
    if (!Number.isFinite(date.getTime())) return 0;
    const month = date.getMonth();
    const safeDay = month === 1 && date.getDate() === 29 ? 28 : date.getDate();
    const reference = new Date(2001, month, safeDay);
    const start = new Date(2001, 0, 1);
    return Math.max(0, Math.min(364, Math.round((reference - start) / 86400000)));
  }

